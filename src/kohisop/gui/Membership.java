    private void buttonDaftarMemberActionPerformed(java.awt.event.ActionEvent evt) {
        String nama = textFieldMasukkanNama.getText().trim();

        if (nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Masukkan nama terlebih dahulu!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Member newMember = new Member(nama);
        databaseMember.add(newMember);
        currentMember = newMember;

        JOptionPane.showMessageDialog(this,
                "Berhasil mendaftar!\nNama: " + newMember.getNama() + "\nKode: " + newMember.getKodeMember(),
                "Registrasi Member", JOptionPane.INFORMATION_MESSAGE);

        textAreaMethod.setText("Member: " + newMember.getNama() + "\nKode: " + newMember.getKodeMember() + "\nPoin: " + newMember.getPoin());
        textFieldMasukkanNama.setText("");
    }

    private void buttonLanjutkanPembayaranActionPerformed(java.awt.event.ActionEvent evt) {
        // Hitung total belanja dari tabel
        double totalBelanja = hitungTotalBelanja();

        if (totalBelanja <= 0) {
            JOptionPane.showMessageDialog(this, "Pesanan kosong!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Create ItemPesanan list with quantities from table
        ArrayList<ItemPesanan> pesananItems = new ArrayList<>();
        for (int i = 0; i < tabelAturPesanan.getRowCount(); i++) {
            int qty = 0;
            try {
                qty = Integer.parseInt(tabelAturPesanan.getValueAt(i, 5).toString());
            } catch (NumberFormatException e) {
                qty = 0;
            }

            if (qty > 0) {
                MenuItem item = pesananDiterima.get(i);
                ItemPesanan itemPesanan = new ItemPesanan(item, qty);
                pesananItems.add(itemPesanan);
            }
        }

        // Buka halaman Pembayaran dan pass data
        Pembayaran pembayaran = new Pembayaran(currentMember, pesananItems, totalBelanja);
        pembayaran.setVisible(true);

        // Close Membership window
        this.dispose();
    }

    private void buttonTambahQtyActionPerformed(java.awt.event.ActionEvent evt) {
        int selectedRow = tabelAturPesanan.getSelectedRow();
        if (selectedRow >= 0) {
            int currentQty = (int) tabelAturPesanan.getValueAt(selectedRow, 5);
            int maxQty = (int) tabelAturPesanan.getValueAt(selectedRow, 4);

            if (currentQty < maxQty) {
                tabelAturPesanan.setValueAt(currentQty + 1, selectedRow, 5);
            }
        }
    }

    private void buttonKurangQtyActionPerformed(java.awt.event.ActionEvent evt) {
        int selectedRow = tabelAturPesanan.getSelectedRow();
        if (selectedRow >= 0) {
            int currentQty = (int) tabelAturPesanan.getValueAt(selectedRow, 5);

            if (currentQty > 0) {
                tabelAturPesanan.setValueAt(currentQty - 1, selectedRow, 5);
            }
        }
    }

    private void setColumnWidths() {
        tabelAturPesanan.getColumnModel().getColumn(0).setPreferredWidth(70);   // Kode
        tabelAturPesanan.getColumnModel().getColumn(1).setPreferredWidth(180);  // Nama (diperlebar)
        tabelAturPesanan.getColumnModel().getColumn(2).setPreferredWidth(150);  // Kategori (diperlebar)
        tabelAturPesanan.getColumnModel().getColumn(3).setPreferredWidth(100);  // Harga
        tabelAturPesanan.getColumnModel().getColumn(4).setPreferredWidth(100);  // Max. Qty
        tabelAturPesanan.getColumnModel().getColumn(5).setPreferredWidth(80);   // Qty
    }

    private void isiTabelPesanan() {
        javax.swing.table.DefaultTableModel modelPesanan
                = new javax.swing.table.DefaultTableModel(
                        new Object[][]{},
                        new String[]{
                            "Kode", "Nama", "Kategori", "Harga", "Max. Qty", "Qty"
                        }
                ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 5; // Hanya kolom Qty yang editable
            }
        };

        for (MenuItem item : pesananDiterima) {
            // Tentukan Max Qty berdasarkan tipe item
            int maxQty;
            if (item instanceof kohisop.model.Makanan) {
                maxQty = kohisop.model.Makanan.MAX_KUANTITAS;
            } else if (item instanceof kohisop.model.Minuman) {
                maxQty = kohisop.model.Minuman.MAX_KUANTITAS;
            } else {
                maxQty = 0;
            }

            modelPesanan.addRow(new Object[]{
                item.getKode(),
                item.getNama(),
                item.getKategori(),
                "Rp" + String.format("%.0f", item.getHarga()),
                maxQty,
                0 // Qty awal 0
            });
        }

        tabelAturPesanan.setModel(modelPesanan);

        // Set editor untuk kolom Qty menggunakan JTextField
        javax.swing.JTextField textField = new javax.swing.JTextField();
        tabelAturPesanan.getColumnModel().getColumn(5).setCellEditor(new javax.swing.DefaultCellEditor(textField));

        setColumnWidths();
    }

    private Member cariMemberByKode(String kode) {
        for (Member m : databaseMember) {
            if (m.getKodeMember().equalsIgnoreCase(kode)) {
                return m;
            }
        }
        return null;
    }

    private double hitungTotalBelanja() {
        double total = 0;
        for (int i = 0; i < tabelAturPesanan.getRowCount(); i++) {
            String hargaStr = tabelAturPesanan.getValueAt(i, 3).toString().replace("Rp", "").trim();

            // Parse qty dari String (karena di-edit pakai JTextField)
            int qty = 0;
            try {
                qty = Integer.parseInt(tabelAturPesanan.getValueAt(i, 5).toString());
            } catch (NumberFormatException e) {
                qty = 0;
            }

            try {
                double harga = Double.parseDouble(hargaStr);
                total += harga * qty;
            } catch (NumberFormatException e) {
                // Skip jika tidak valid
            }
        }
        return total;
    }

