    private void buttonCariMemberActionPerformed(java.awt.event.ActionEvent evt) {
        String kode = textFieldMasukkanKode.getText().trim();

        if (kode.isEmpty() || kode.equals("Masukan Kode di sini")) {
            JOptionPane.showMessageDialog(this, "Masukkan kode member terlebih dahulu!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Member found = cariMemberByKode(kode);
        if (found != null) {
            currentMember = found;
            JOptionPane.showMessageDialog(this,
                    "Selamat datang, " + found.getNama() + "!\nPoin Anda: " + found.getPoin(),
                    "Member Ditemukan", JOptionPane.INFORMATION_MESSAGE);
            textAreaMethod.setText("Member: " + found.getNama() + "\nKode: " + found.getKodeMember() + "\nPoin: " + found.getPoin());
        } else {
            JOptionPane.showMessageDialog(this, "Member tidak ditemukan!", "Error", JOptionPane.ERROR_MESSAGE);
            currentMember = null;
        }
    }

